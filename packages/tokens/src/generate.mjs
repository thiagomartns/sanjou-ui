import {
  CHROMA_FACTOR,
  GRAY_CHROMA,
  LIGHTNESS,
  RADIUS,
  SCALES,
  SCALE_DEFS,
  SEMANTIC,
  CONTRAST_RULES,
  EASINGS,
  FONTS,
  FONT_WEIGHTS,
  SHADOWS,
  SHADOW_COLOR,
  SPACING_STEPS,
  TYPE_SCALE,
} from './config.mjs';
import { contrast, hexToComponents, hslToHex, oklchToHex } from './color.mjs';

const THEMES = ['light', 'dark'];

/** @returns {{ light: Record<string, {step:number, hex:string, oklch:string}[]>, dark: … }} */
export function buildPalette() {
  const out = { light: {}, dark: {} };
  for (const theme of THEMES) {
    for (const name of SCALES) {
      const def = SCALE_DEFS[name];
      const hover = def.hoverDelta ?? 0.045;
      out[theme][name] = Array.from({ length: 12 }, (_, i) => {
        let L = LIGHTNESS[theme][i];
        if (i === 8) L = def.solid[theme];
        if (i === 9) L = theme === 'light' ? def.solid.light - hover : def.solid.dark + hover;
        if (def.lightText && theme === 'light' && i >= 10) L = def.lightText[i - 10];
        const C = def.neutral ? GRAY_CHROMA[theme][i] : def.chroma * CHROMA_FACTOR[theme][i];
        const { hex, C: fitted } = oklchToHex(L, C, def.hue);
        return {
          step: i + 1,
          hex,
          oklch: `oklch(${L.toFixed(3)} ${fitted.toFixed(3)} ${def.hue})`,
        };
      });
    }
  }
  return out;
}

/** Splits `gray.12/50` into its base (`gray.12`) and alpha (0.5); alpha is 1 without a suffix. */
export function parseRef(ref) {
  const [base, percent] = ref.split('/');
  return { base, alpha: percent === undefined ? 1 : Number(percent) / 100 };
}

/** Hex of a ref's base color, ignoring alpha. */
export function resolve(palette, theme, ref) {
  const { base } = parseRef(ref);
  if (base.startsWith('#')) return base;
  const [scale, step] = base.split('.');
  return palette[theme][scale][Number(step) - 1].hex;
}

/** `#rrggbbaa` for a ref with alpha, so DTCG and Figma plugins keep the transparency. */
const hexWithAlpha = (palette, theme, ref) =>
  resolve(palette, theme, ref) +
  Math.round(parseRef(ref).alpha * 255)
    .toString(16)
    .padStart(2, '0');

export function checkContrast(palette) {
  const results = [];
  for (const theme of THEMES) {
    const t = theme === 'light' ? 0 : 1;
    for (const [fg, bg, min] of CONTRAST_RULES) {
      for (const k of [fg, bg])
        if (parseRef(SEMANTIC[k][t]).alpha !== 1)
          throw new Error(`Contrast rule uses ${k}, which has alpha: contrast would be wrong.`);
      const ratio = contrast(
        resolve(palette, theme, SEMANTIC[fg][t]),
        resolve(palette, theme, SEMANTIC[bg][t]),
      );
      results.push({
        theme,
        fg,
        bg,
        min,
        ratio: Math.round(ratio * 100) / 100,
        pass: ratio >= min,
      });
    }
  }
  return results;
}

const HEADER = '/* Generated by packages/tokens/scripts/build.mjs — do not edit by hand. */\n';
const px = (v) => (v === 0 ? '0' : `${v}px`);
const cssShadow = ({ layers }) =>
  layers
    .map(
      ([x, y, blur, spread, a]) =>
        `${px(x)} ${px(y)} ${px(blur)} ${px(spread)} hsl(var(--shadow-color) / ${a})`,
    )
    .join(', ');
const CSS_SHADOWS = Object.fromEntries(Object.entries(SHADOWS).map(([k, v]) => [k, cssShadow(v)]));
const cssShadowColor = (theme) => {
  const [h, sat, l] = SHADOW_COLOR[theme];
  return `${h} ${sat}% ${l}%`;
};
const fontSans = `var(--font-geist-sans, "${FONTS.sans}"), ui-sans-serif, system-ui, sans-serif`;
const fontMono = (fallbacks) => `var(--font-geist-mono, "${FONTS.mono}"), ${fallbacks}`;
const cssRef = (ref) => {
  const { base, alpha } = parseRef(ref);
  const color =
    base === '#ffffff'
      ? 'oklch(1 0 0)'
      : base.startsWith('#')
        ? base
        : `var(--${base.replace('.', '-')})`;
  return alpha === 1 ? color : `color-mix(in oklch, ${color} ${alpha * 100}%, transparent)`;
};

export function buildCss(palette) {
  const lines = [HEADER, '@custom-variant dark (&:where(.dark, .dark *));', ''];
  for (const theme of THEMES) {
    const t = theme === 'light' ? 0 : 1;
    lines.push(theme === 'light' ? ':root {' : '.dark {', `  color-scheme: ${theme};`);
    for (const name of SCALES)
      for (const s of palette[theme][name])
        lines.push(`  --${name}-${s.step}: ${s.oklch}; /* ${s.hex} */`);
    lines.push('');
    for (const [k, refs] of Object.entries(SEMANTIC)) lines.push(`  --${k}: ${cssRef(refs[t])};`);
    if (theme === 'light') lines.push('  --radius: 0.5rem;');
    lines.push(`  --shadow-color: ${cssShadowColor(theme)};`);
    lines.push('}', '');
  }
  lines.push('@theme inline {');
  for (const name of SCALES)
    for (let i = 1; i <= 12; i++) lines.push(`  --color-${name}-${i}: var(--${name}-${i});`);
  for (const k of Object.keys(SEMANTIC)) lines.push(`  --color-${k}: var(--${k});`);
  lines.push(
    '',
    `  --font-sans: ${fontSans};`,
    `  --font-mono: ${fontMono('ui-monospace, "SFMono-Regular", monospace')};`,
    '',
    '  --radius-sm: calc(var(--radius) - 4px);',
    '  --radius-md: calc(var(--radius) - 2px);',
    '  --radius-lg: var(--radius);',
    '  --radius-xl: calc(var(--radius) + 4px);',
    '',
    ...Object.entries(CSS_SHADOWS).map(([k, v]) => `  --shadow-${k}: ${v};`),
    '',
    ...Object.entries(EASINGS).map(([k, v]) => `  --ease-${k}: ${v};`),
    '}',
    '',
    '@theme {',
    '  /* UI-dense type scale. App default text is text-base = 14px. */',
  );
  for (const [n, size, lh, ls] of TYPE_SCALE) {
    let l = `  --text-${n}: ${size / 16}rem; --text-${n}--line-height: ${lh / 16}rem;`;
    if (ls) l += ` --text-${n}--letter-spacing: ${ls}em;`;
    lines.push(l);
  }
  lines.push(
    '}',
    '',
    '@layer base {',
    '  *, ::before, ::after { border-color: var(--border); }',
    '  body { background: var(--background); color: var(--foreground); font-family: var(--font-sans); font-size: var(--text-base); line-height: var(--text-base--line-height); -webkit-font-smoothing: antialiased; }',
    '  :focus-visible { outline: 2px solid var(--ring); outline-offset: 2px; }',
    '}',
    '',
  );
  return lines.join('\n');
}

/** W3C DTCG: one object per theme for colors, plus dimensions and typography. */
export function buildDtcg(palette) {
  const color = (hex) => ({ $type: 'color', $value: hex });
  const out = { $description: 'Sanjou UI tokens (W3C DTCG). Generated — do not edit.' };
  for (const theme of THEMES) {
    const t = theme === 'light' ? 0 : 1;
    out[theme] = {
      scale: Object.fromEntries(
        SCALES.map((s) => [
          s,
          Object.fromEntries(palette[theme][s].map((x) => [String(x.step), color(x.hex)])),
        ]),
      ),
      ...Object.fromEntries(
        Object.entries(SEMANTIC).map(([k, r]) => [
          k,
          // An alias cannot carry alpha: refs with alpha get the resolved #rrggbbaa.
          parseRef(r[t]).alpha !== 1
            ? color(hexWithAlpha(palette, theme, r[t]))
            : r[t].startsWith('#')
              ? color(r[t])
              : { $type: 'color', $value: `{${theme}.scale.${r[t]}}` },
        ]),
      ),
    };
  }
  out.radius = Object.fromEntries(
    Object.entries(RADIUS).map(([k, v]) => [
      k,
      { $type: 'dimension', $value: { value: v, unit: 'px' } },
    ]),
  );
  out.space = Object.fromEntries(
    SPACING_STEPS.map((k) => [
      String(k).replace('.', '_'),
      { $type: 'dimension', $value: { value: k * 4, unit: 'px' } },
    ]),
  );
  out.text = Object.fromEntries(
    TYPE_SCALE.map(([n, size, lh, ls]) => [
      n,
      {
        $type: 'typography',
        $value: {
          fontFamily: FONTS.sans,
          fontSize: { value: size, unit: 'px' },
          lineHeight: lh / size,
          letterSpacing: { value: ls, unit: 'em' },
        },
      },
    ]),
  );
  return out;
}

const figmaScopes = (k) => {
  if (['border', 'input', 'ring'].includes(k)) return ['STROKE_COLOR', 'EFFECT_COLOR'];
  if (k === 'foreground' || k.endsWith('-foreground') || k.endsWith('-text'))
    return ['TEXT_FILL', 'SHAPE_FILL', 'STROKE_COLOR'];
  return ['FRAME_FILL', 'SHAPE_FILL'];
};

/** Figma variables, one file per collection mode. `native` = Figma's own export shape; `hex` = plain strings for plugins. */
export function buildFigma(palette, format) {
  const val = (hex, alpha = 1) =>
    format === 'native'
      ? { colorSpace: 'srgb', components: hexToComponents(hex), alpha, hex: hex.toUpperCase() }
      : alpha === 1
        ? hex
        : hex +
          Math.round(alpha * 255)
            .toString(16)
            .padStart(2, '0');
  const files = {};
  for (const theme of THEMES) {
    const t = theme === 'light' ? 0 : 1;
    const doc = { scale: {} };
    for (const s of SCALES)
      doc.scale[s] = Object.fromEntries(
        palette[theme][s].map((x) => [
          String(x.step),
          {
            $type: 'color',
            $value: val(x.hex),
            // Components only use the scale for hover/active: keep it out of the published library.
            $extensions: {
              'com.figma.scopes': ['ALL_SCOPES'],
              'com.figma.hiddenFromPublishing': true,
            },
          },
        ]),
      );
    for (const [k, r] of Object.entries(SEMANTIC)) {
      const { alpha } = parseRef(r[t]);
      doc[k] = {
        $type: 'color',
        // Figma aliases cannot carry alpha either: resolve refs with alpha.
        $value:
          alpha !== 1
            ? val(resolve(palette, theme, r[t]), alpha)
            : r[t].startsWith('#')
              ? val(r[t])
              : `{scale.${r[t]}}`,
        $extensions: { 'com.figma.scopes': figmaScopes(k) },
      };
    }
    // One color per shadow layer (shadow color + the layer's alpha), so effect styles follow the mode.
    doc.shadow = Object.fromEntries(
      Object.entries(SHADOWS).map(([k, { layers }]) => [
        k,
        Object.fromEntries(
          layers.map((l, i) => [
            String(i + 1),
            {
              $type: 'color',
              $value: val(hslToHex(SHADOW_COLOR[theme]), l[4]),
              $extensions: {
                'com.figma.scopes': ['EFFECT_COLOR'],
                'com.figma.hiddenFromPublishing': true,
              },
            },
          ]),
        ),
      ]),
    );
    files[`Color.${theme === 'light' ? 'Light' : 'Dark'}.tokens.json`] = doc;
  }
  files['Dimension.Value.tokens.json'] = {
    space: Object.fromEntries(
      SPACING_STEPS.map((k) => [
        String(k).replace('.', '_'),
        {
          $type: 'number',
          $value: k * 4,
          $extensions: { 'com.figma.scopes': ['GAP', 'WIDTH_HEIGHT'] },
        },
      ]),
    ),
    radius: Object.fromEntries(
      Object.entries(RADIUS).map(([k, v]) => [
        k,
        { $type: 'number', $value: v, $extensions: { 'com.figma.scopes': ['CORNER_RADIUS'] } },
      ]),
    ),
  };
  return files;
}

const FIGMA_FONT_STYLE = { 400: 'Regular', 500: 'Medium', 600: 'SemiBold' };
/** Mono sizes the components use (`font-mono` with text-xs / text-sm). */
const MONO_SIZES = ['xs', 'sm'];

/**
 * Text and effect styles for Figma. Figma's variable importer does not create styles, so these
 * are applied by script (Plugin API), matching by name. Effect colors point at `shadow.*` variables.
 */
export function buildFigmaStyles() {
  const text = {};
  const textStyle = (family, weight, [, size, lh, ls], description) => ({
    fontFamily: family,
    fontStyle: FIGMA_FONT_STYLE[weight],
    fontWeight: weight,
    fontSize: size,
    lineHeight: { unit: 'PIXELS', value: lh },
    letterSpacing: { unit: 'PERCENT', value: Math.round(ls * 1000) / 10 },
    description,
  });
  for (const step of TYPE_SCALE)
    for (const [w, weight] of Object.entries(FONT_WEIGHTS))
      text[`${step[0]}/${w}`] = textStyle(
        FONTS.sans,
        weight,
        step,
        `text-${step[0]} · ${step[1]}/${step[2]}${step[3] ? ` · ${step[3]}em` : ''} · font-${w === 'regular' ? 'normal' : w}`,
      );
  for (const n of MONO_SIZES)
    text[`mono/${n}`] = textStyle(
      FONTS.mono,
      FONT_WEIGHTS.regular,
      TYPE_SCALE.find((t) => t[0] === n),
      `font-mono text-${n}`,
    );
  const effect = Object.fromEntries(
    Object.entries(SHADOWS).map(([k, { use, layers }]) => [
      `shadow-${k}`,
      {
        description: `shadow-${k} · ${use}`,
        layers: layers.map(([x, y, blur, spread], i) => ({
          type: 'DROP_SHADOW',
          offset: { x, y },
          radius: blur,
          spread,
          color: `{shadow.${k}.${i + 1}}`,
        })),
      },
    ]),
  );
  return {
    $description:
      'Sanjou UI text and effect styles for Figma. Generated from packages/tokens/src/config.mjs — do not edit.',
    text,
    effect,
  };
}

// Sanjou mark: an arc in ink and a triangle in indigo (48×48 grid).
const MARK_ARC = 'M5 43 A31 31 0 0 1 36 12 A27 27 0 0 0 16 43 Z';
const MARK_TRIANGLE = 'M28 43 L36 30 L44 43 Z';

/** Ink + accent of the mark per theme. Dark uses brand-text: indigo-9 is too dim on a dark page. */
export function logoColors(palette, theme) {
  const t = theme === 'light' ? 0 : 1;
  const accent = theme === 'light' ? SEMANTIC.brand : SEMANTIC['brand-text'];
  return {
    ink: resolve(palette, theme, SEMANTIC.foreground[t]),
    accent: resolve(palette, theme, accent[t]),
  };
}

/** Static mark for one theme (README, docs). */
export function buildLogo(palette, theme) {
  const { ink, accent } = logoColors(palette, theme);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48" viewBox="0 0 48 48">
  <path d="${MARK_ARC}" fill="${ink}"/>
  <path d="${MARK_TRIANGLE}" fill="${accent}"/>
</svg>
`;
}

/** Favicon that follows the browser color scheme. */
export function buildFavicon(palette) {
  const light = logoColors(palette, 'light');
  const dark = logoColors(palette, 'dark');
  return `<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48" viewBox="0 0 48 48">
  <style>
    .ink { fill: ${light.ink}; }
    .accent { fill: ${light.accent}; }
    @media (prefers-color-scheme: dark) {
      .ink { fill: ${dark.ink}; }
      .accent { fill: ${dark.accent}; }
    }
  </style>
  <path class="ink" d="${MARK_ARC}"/>
  <path class="accent" d="${MARK_TRIANGLE}"/>
</svg>
`;
}

/** shadcn registry item that installs the theme into a consumer's globals.css. */
export function buildRegistryTheme(palette) {
  const vars = (theme) => {
    const t = theme === 'light' ? 0 : 1;
    const o = {};
    for (const s of SCALES) for (const x of palette[theme][s]) o[`${s}-${x.step}`] = x.oklch;
    for (const [k, r] of Object.entries(SEMANTIC)) o[k] = cssRef(r[t]);
    if (theme === 'light') o.radius = '0.5rem';
    return o;
  };
  const theme = {
    'font-sans': fontSans,
    'font-mono': fontMono('ui-monospace, monospace'),
    'radius-sm': 'calc(var(--radius) - 4px)',
    'radius-md': 'calc(var(--radius) - 2px)',
    'radius-lg': 'var(--radius)',
    'radius-xl': 'calc(var(--radius) + 4px)',
  };
  for (const [k, v] of Object.entries(CSS_SHADOWS)) theme[`shadow-${k}`] = v;
  for (const [k, v] of Object.entries(EASINGS)) theme[`ease-${k}`] = v;
  for (const s of SCALES)
    for (let i = 1; i <= 12; i++) theme[`color-${s}-${i}`] = `var(--${s}-${i})`;
  for (const k of Object.keys(SEMANTIC)) theme[`color-${k}`] = `var(--${k})`;
  for (const [n, size, lh, ls] of TYPE_SCALE) {
    theme[`text-${n}`] = `${size / 16}rem`;
    theme[`text-${n}--line-height`] = `${lh / 16}rem`;
    if (ls) theme[`text-${n}--letter-spacing`] = `${ls}em`;
  }
  return {
    name: 'theme',
    type: 'registry:theme',
    title: 'Sanjou theme',
    description:
      'Sanjou UI color scales, semantic tokens, radius, shadows, easing and type scale (light + dark). Generated from packages/tokens.',
    cssVars: { theme, light: vars('light'), dark: vars('dark') },
    // What cssVars cannot carry. The shadcn CLI would read the shadow color as a legacy HSL color
    // (wrapping it in hsl() and adding a --color-* utility), so it goes here, untouched.
    css: {
      ':root': { 'color-scheme': 'light', '--shadow-color': cssShadowColor('light') },
      '.dark': { 'color-scheme': 'dark', '--shadow-color': cssShadowColor('dark') },
      '@layer base': {
        body: {
          'font-size': 'var(--text-base)',
          'line-height': 'var(--text-base--line-height)',
          '-webkit-font-smoothing': 'antialiased',
        },
      },
    },
  };
}

export function buildContrastReport(results) {
  const rows = results.map(
    (r) =>
      `| ${r.theme} | \`${r.fg}\` on \`${r.bg}\` | ${r.ratio.toFixed(2)}:1 | ≥${r.min} | ${r.pass ? '✅' : '❌'} |`,
  );
  return [
    '# Contrast report',
    '',
    'Generated — WCAG 2 relative-luminance contrast.',
    '',
    '| theme | pair | ratio | min | |',
    '|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}
